function isHoliday(dateStr) {
  return HOLIDAYS.has(dateStr);
}

function isWeekendOrHoliday(dateStr) {
  const dow = new Date(dateStr).getDay();
  return dow === 0 || dow === 6 || isHoliday(dateStr);
}

